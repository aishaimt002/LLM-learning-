#import os 
import os #read environment variables 
from dotenv import load_dotenv  #load information presnet inside the .env 
from google import genai # communicate with gemini

load_dotenv()

#now we are retrieving an environment varaibles through a function and the name of the 
# variable we're looking for is GEMINI API KEY
api_key = os.getenv("GEMINI_API_KEY")

# now we need to check if the api key exists inside the env file or not
if not api_key:
    raise ValueError("Gemini key not found inside the .env file")

#creating a clinet who can send request to gemini directly
gemini_client = genai.Client(api_key=api_key)

#now select the MODEL 
MODEL = "gemini-3.5-flash-lite"

prompt="Is AI is taking every software engineer job"

#now sending the request to GEMINI 
response = gemini_client.models.generate_content(
    model=MODEL,
    contents=prompt,
)

print("\n-----GEMINI RESPONSE----")
#actual text generated by gemini 
print(response.text)
#retrieving token usage 
usage = response.usage_metadata 

print("\n ------------ GEMINI RESPONSE --------------")
print(f"Input tokens:{usage.prompt_token_count}") #prompt token count 
print(f"Output tokens: {usage.candidates_token_count}") #user token count 

#total token 
total_tokens = (usage.prompt_token_count + usage.candidates_token_count)

print(f"Total tokens:{total_tokens}")

